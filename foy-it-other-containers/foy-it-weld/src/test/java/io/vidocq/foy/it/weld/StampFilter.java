package io.vidocq.foy.it.weld;

import jakarta.enterprise.context.Dependent;
import jakarta.inject.Inject;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebFilter;
import jakarta.servlet.http.HttpFilter;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;

/** A filter that is a CDI bean: it stamps the response with an injected bean's answer. */
@Dependent
@WebFilter("/greet/*")
public class StampFilter extends HttpFilter {

    @Inject
    Greeter greeter;

    @Override
    protected void doFilter(HttpServletRequest request, HttpServletResponse response, FilterChain chain)
            throws IOException, ServletException {
        response.setHeader("X-Stamp", greeter.greet("filter"));
        chain.doFilter(request, response);
    }
}
