package io.vidocq.foy.zap;

import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebFilter;
import jakarta.servlet.http.HttpFilter;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;

/**
 * The security headers a careful application sets, as Chappe's scan sets them through its configuration:
 * what ZAP then reports is the container's own behaviour, not a header only the application can choose.
 */
@WebFilter("/*")
public class SecurityHeadersFilter extends HttpFilter {

    private static final long serialVersionUID = 1L;

    @Override
    protected void doFilter(HttpServletRequest req, HttpServletResponse res, FilterChain chain)
            throws IOException, ServletException {
        res.setHeader("Content-Security-Policy", "default-src 'self'; frame-ancestors 'none'; form-action 'self'");
        res.setHeader("X-Content-Type-Options", "nosniff");
        res.setHeader("X-Frame-Options", "DENY");
        res.setHeader("Referrer-Policy", "strict-origin-when-cross-origin");
        res.setHeader("Permissions-Policy", "camera=(), geolocation=(), microphone=()");
        chain.doFilter(req, res);
    }
}
