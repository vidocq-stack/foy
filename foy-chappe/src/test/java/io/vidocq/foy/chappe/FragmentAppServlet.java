package io.vidocq.foy.chappe;

import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;

/**
 * Servlet of the application itself (test classes), declared by an explicit web.xml of
 * {@code FoyChappeBootFragmentsTest}. It is a top-level type because the initializers that test
 * compiles, in other packages, instantiate it.
 */
public class FragmentAppServlet extends HttpServlet {
    @Override
    protected void doGet(HttpServletRequest q, HttpServletResponse r) throws IOException {
        Object listened = q.getAttribute("exl");
        r.getWriter().write(listened == null ? "app" : "app:" + listened);
    }
}
